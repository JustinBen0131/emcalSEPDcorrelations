    inline constexpr int returnTile(int ch)
    {
        return energyToTile[ch];          // array lookup, no function call
    }



    inline constexpr int returnRing(int ch)
    {
        return (energyToTile[ch] + 1) / 2;   // 0 … 15
    }

    inline constexpr int returnArm   (int ch) {
        // 0 is south, 1 is north
        if ( ch >= 384 && ch <= 767 ) return 0;
        else if ( ch <= 383 && ch >= 0 ) return 1;
        else return -1;
    }
